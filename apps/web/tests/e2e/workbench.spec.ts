import { readFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'

async function authenticate(page: Page, username = 'admin@northstar.example.com') {
  const response = await page.request.post('/api/v1/auth/login', { data: { username, password: process.env.EVALBOARD_DEMO_PASSWORD ?? 'Demo123!' } })
  expect(response.ok()).toBeTruthy()
}

test('overview uses workspace evidence and labels the synthetic scope', async ({ page }) => {
  await authenticate(page)
  const datasets = await (await page.request.get('/api/v1/datasets')).json() as { items: Array<{ case_count: number }> }
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page).toHaveURL(/\/overview$/)
  await expect(page.getByRole('heading', { name: 'Evaluation workbench' })).toBeVisible()
  await expect(page.getByText('Live-model quality has not been measured.', { exact: false })).toBeVisible()
  await expect(page.locator('.overview-stat').first().locator('strong')).toHaveText(String(datasets.items.reduce((sum, item) => sum + item.case_count, 0)))
  await expect(page.locator('.overview-run').first()).toBeVisible()
  await page.getByRole('link', { name: 'Explore the workflow' }).click()
  await expect(page.getByRole('heading', { name: 'From change to evidence' })).toBeInViewport()
  expect(errors).toEqual([])
})

test('experiment discovery preserves filters and recovers from no matches', async ({ page }) => {
  await authenticate(page)
  await page.goto('/experiments')
  await page.getByLabel('Search experiments').fill('no matching experiment 987654')
  await expect(page.getByRole('heading', { name: 'No matching experiments' })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Search experiments')).toHaveValue('no matching experiment 987654')
  await page.getByRole('button', { name: 'Clear filters' }).first().click()
  await expect(page.locator('.experiment-item').first()).toBeVisible()
  await page.getByLabel('Filter experiment status').selectOption('attention')
  await expect(page).toHaveURL(/status=attention/)
  const experiments = await (await page.request.get('/api/v1/experiments')).json() as { items: Array<{ status: string }> }
  await expect(page.locator('.experiment-item')).toHaveCount(experiments.items.filter(item => ['failed', 'uncertain', 'budget_exhausted'].includes(item.status)).length)
  if (!experiments.items.some(item => ['failed', 'uncertain', 'budget_exhausted'].includes(item.status))) await expect(page.getByRole('heading', { name: 'No matching experiments' })).toBeVisible()
  const statuses = await page.locator('.experiment-item .status').allTextContents()
  expect(statuses.every(status => ['failed', 'uncertain', 'budget exhausted'].includes(status.trim()))).toBeTruthy()
  await page.getByLabel('Sort experiments').selectOption('oldest')
  await expect(page).toHaveURL(/sort=oldest/)
})

test('appearance previews, applies, persists, exports and validates imports', async ({ page }) => {
  await authenticate(page)
  await page.goto('/appearance')
  await page.getByLabel('Product name').fill('Atlas Quality')
  await page.getByLabel('Tagline').fill('Decisions with a trace.')
  await page.getByRole('radio', { name: 'Iris' }).check()
  await page.getByRole('radio', { name: /Compact/ }).check()
  await expect(page.locator('.preview-brand')).toHaveText('Atlas Quality')
  await expect(page.locator('.side-rail .brand')).toHaveText('EvalBoard')
  await page.getByRole('button', { name: 'Apply appearance' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-density', 'compact')
  await expect(page.locator('html')).toHaveAttribute('data-accent', 'iris')
  await page.reload()
  await expect(page.locator('.side-rail .brand')).toHaveText('Atlas Quality')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export applied appearance' }).click()
  const download = await downloadEvent
  const exported = JSON.parse(await readFile((await download.path())!, 'utf8')) as { version: number; appearance: { name: string; accent: string } }
  expect(exported.version).toBe(1)
  expect(exported.appearance.name).toBe('Atlas Quality')
  await page.getByLabel('Appearance JSON file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"version":1,"appearance":{"name":"Broken"}}') })
  await expect(page.getByRole('alert')).toContainText('Tagline')
  await expect(page.locator('.side-rail .brand')).toHaveText('Atlas Quality')
  await page.getByLabel('Appearance JSON file').setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, appearance: { name: 'Client Workbench', tagline: 'Inspect every release.', accent: 'forest', density: 'comfortable', collapsed: false } })) })
  await expect(page.locator('.preview-brand')).toHaveText('Client Workbench')
  await expect(page.locator('.side-rail .brand')).toHaveText('Atlas Quality')
  await page.getByRole('button', { name: 'Apply appearance' }).click()
  await expect(page.locator('.side-rail .brand')).toHaveText('Client Workbench')
  await expect(page.locator('html')).toHaveAttribute('data-accent', 'forest')
  await page.getByRole('button', { name: 'Preview defaults' }).click()
  await page.getByRole('button', { name: 'Apply appearance' }).click()
  await expect(page.locator('.side-rail .brand')).toHaveText('EvalBoard')
})

